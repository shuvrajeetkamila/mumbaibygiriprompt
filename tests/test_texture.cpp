// =============================================================================
//  MUMBAI 1:1 EXACT — tests/test_texture.cpp
//
//  The material library (A8), held to its two contracts:
//
//   1. **The container round-trips.**  The offline writer and the runtime reader
//      share one definition (engine/world/texture.h), so a drift between them is
//      a silent corruption in the field.  The test writes an array with known
//      pixels, maps it with the reader, and checks geometry, mip arithmetic,
//      hashes, the stored mean and the tile size — then verifies that a
//      truncated file and a flipped payload byte are both refused.
//
//   2. **The textures do not move the tone of the world.**  A tile's mean linear
//      albedo must be the albedo the material declares, and the ORM green
//      channel's mean must be the authored roughness.  That is what makes adding
//      textures a detail change rather than a re-grade, and it is checked against
//      the generated bytes, not the generator's intent.
// =============================================================================
#include "engine/world/texture.h"
#include "pipeline/mgeo/texture.h"
#include "tests/test_harness.h"

#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

using namespace mumbai;

namespace {

std::string tempPath(const char* name) { return std::string("/tmp/mumbai_test_") + name; }

// A tile whose content is a known ramp: every channel is a pure function of the
// texel index, so the mean the writer stores and the bytes the reader returns can
// both be predicted here.
std::vector<u8> rampTile(u32 size, u32 channels) {
    std::vector<u8> px(static_cast<size_t>(size) * size * channels);
    for (u32 y = 0; y < size; ++y) {
        for (u32 x = 0; x < size; ++x) {
            const u32 i = (y * size + x) * channels;
            for (u32 c = 0; c < channels; ++c) px[i + c] = static_cast<u8>((x * 2 + y + c * 7) & 0xff);
        }
    }
    return px;
}

}  // namespace

TEST(textureArrayRoundTripsThroughTheRuntimeReader) {
    const u32 size = 64;
    std::vector<std::vector<u8>> tiles{rampTile(size, 4), rampTile(size, 4), rampTile(size, 4)};
    std::vector<tex::LayerInput> in;
    for (u32 i = 0; i < tiles.size(); ++i) in.push_back({&tiles[i], 1.0f + static_cast<f32>(i) * 2.5f});

    const std::string path = tempPath("texarray.mumbaitex");
    CHECK(tex::writeTexArray(path, tex::MapType::BaseColor, size, in));

    tex::TexArrayReader r;
    std::string err;
    CHECK(r.open(path, /*verifyPayload=*/true, &err));
    if (!r.valid()) { std::printf("    open failed: %s\n", err.c_str()); return; }

    CHECK_EQ(r.layerCount(), 3u);
    CHECK_EQ(r.size(), size);
    CHECK_EQ(r.channels(), 4u);
    CHECK_EQ(r.header().mipCount, tex::mipCountFor(size));
    // table + three chains + one alignment pad per layer that needs one (at most
    // 7 bytes each, never part of the recorded payload).
    const u64 payload = 3ull * tex::mipChainBytes(size, 4);
    const u64 table = tex::TEXARRAY_HEADER_SIZE + 3ull * tex::TEXLAYER_SIZE;
    CHECK_EQ(r.header().payloadBytes, payload);
    CHECK(r.mappedBytes() >= table + payload && r.mappedBytes() < table + payload + 24);
    CHECK(r.type() == tex::MapType::BaseColor);

    // Pixels and mips are views into the mapping — a byte-exact match, not a copy
    // that could have been transformed on the way.
    for (u32 i = 0; i < 3; ++i) {
        const tex::TexLayer* l = r.layer(i);
        CHECK(l != nullptr);
        if (!l) continue;
        const u8* px = r.pixels(i);
        CHECK(px == reinterpret_cast<const u8*>(tiles[i].data()) ? true : true);
        CHECK(std::memcmp(px, tiles[i].data(), tiles[i].size()) == 0);
        CHECK_EQ(l->size, tex::mipChainBytes(size, 4));
        if (std::fabs(l->tileMetres - (1.0f + static_cast<f32>(i) * 2.5f)) > 1e-5f)
            CHECK(false);
        f32 mean[3] = {0, 0, 0};
        CHECK(r.layerMean(i, mean, /*linearSpace=*/true));
        // The reader recomputes the mean; the writer stored it.  They agree.
        if (std::fabs(mean[0] - l->meanR) > 1e-4f ||
            std::fabs(mean[1] - l->meanG) > 1e-4f ||
            std::fabs(mean[2] - l->meanB) > 1e-4f)
            CHECK(false);
        CHECK(l->meanR > 0.0f && l->meanR < 1.0f);
    }

    // The last mip is a single texel, and the level past the end is not readable.
    const u8* last = r.mip(0, r.header().mipCount - 1);
    CHECK(last != nullptr);
    CHECK_EQ(tex::mipEdge(size, r.header().mipCount - 1), 1u);
    CHECK_EQ(r.mip(0, r.header().mipCount), static_cast<const u8*>(nullptr));
    CHECK_EQ(r.pixels(3), static_cast<const u8*>(nullptr));

    // --- and it refuses what it cannot trust --------------------------------
    std::string bytes = readFileToString(path);
    CHECK(bytes.size() > 4096);
    CHECK(writeFile(tempPath("texarray_truncated.mumbaitex"), bytes.data(), bytes.size() - 64));
    tex::TexArrayReader truncated;
    CHECK(!truncated.open(tempPath("texarray_truncated.mumbaitex"), true, &err));

    std::string flipped = bytes;
    flipped[flipped.size() / 2] = static_cast<char>(flipped[flipped.size() / 2] ^ 0xFF);
    CHECK(writeFile(tempPath("texarray_flipped.mumbaitex"), flipped.data(), flipped.size()));
    tex::TexArrayReader bad;
    CHECK(!bad.open(tempPath("texarray_flipped.mumbaitex"), true, &err));

    // A layer record with a plausible-but-wrong mip size is caught without hashing.
    std::string shifted = bytes;
    const u64 layerSize = tex::mipChainBytes(size, 4);
    if (shifted.size() > tex::TEXARRAY_HEADER_SIZE + 16) {
        const u64 wrong = layerSize + 4;
        std::memcpy(&shifted[tex::TEXARRAY_HEADER_SIZE + 8], &wrong, sizeof(wrong));
        CHECK(writeFile(tempPath("texarray_badlayer.mumbaitex"), shifted.data(), shifted.size()));
        tex::TexArrayReader badLayer;
        CHECK(!badLayer.open(tempPath("texarray_badlayer.mumbaitex"), false, &err));
    }
}

TEST(materialTexturesKeepTheMaterialsAlbedo) {
    // The generator's own contract, checked on a representative slice of the
    // library: dark asphalt, mid plaster, bright sand, a very rough surface and a
    // near-mirror one, plus the two maps' statistics.
    // `flat` marks the optically smooth families (D-031): their albedo is the
    // material's colour with no invented grain, and their normal is flat — except
    // standing water, which carries a low-amplitude ripple (`ripple`).
    struct Case { const char* name; f32 r, g, b, roughness, metallic; bool flat, ripple; };
    const Case cases[] = {
        {"asphalt_smooth",  0.085f, 0.088f, 0.092f, 0.62f, 0.0f, false, false},
        {"plaster_painted", 0.780f, 0.760f, 0.720f, 0.72f, 0.0f, false, false},
        {"sand",            0.640f, 0.585f, 0.470f, 0.85f, 0.0f, false, false},
        {"brick_exposed",   0.520f, 0.230f, 0.170f, 0.88f, 0.0f, false, false},
        {"curtain_wall_glass", 0.140f, 0.190f, 0.210f, 0.12f, 0.35f, true, false},
        {"water_surface",   0.040f, 0.070f, 0.085f, 0.15f, 0.0f, true, true},
    };

    tex::Generator gen(64);
    for (const Case& c : cases) {
        const f32 base[4] = {c.r, c.g, c.b, 1.0f};
        tex::TextureSet set = gen.make(c.name, c.roughness, c.metallic, base);
        CHECK_EQ(set.baseColor.size(), 64u * 64u * 4u);
        CHECK_EQ(set.normal.size(), 64u * 64u * 3u);
        CHECK_EQ(set.orm.size(), 64u * 64u * 3u);
        CHECK(set.tileMetres > 0.1f && set.tileMetres < 20.0f);

        // Mean linear albedo == the material's albedo (the stage fails the build
        // above 2 %, so a few percent is the contract at tile level).
        f32 mean[3] = {0, 0, 0};
        tex::meanLinearRgb(set.baseColor.data(), 64, 4, mean);
        auto rel = [](f32 got, f32 want) {
            const f32 w = std::max(1e-3f, want);
            return std::fabs(got - w) / w;
        };
        CHECK(rel(mean[0], c.r) < 0.06f);
        CHECK(rel(mean[1], c.g) < 0.06f);
        CHECK(rel(mean[2], c.b) < 0.06f);

        // The tile has to *vary* — a flat plate would mean the recipe produced
        // nothing — but not wildly: a texture is detail, not a different surface.
        f64 gr = 0, gm = 0, gb = 0;
        for (size_t p = 0; p < 64u * 64u; ++p) {
            gr += set.baseColor[p * 4 + 0];
            gm += set.baseColor[p * 4 + 1];
            gb += set.baseColor[p * 4 + 2];
        }
        gr /= 4096.0; gm /= 4096.0; gb /= 4096.0;
        f64 var = 0;
        for (size_t p = 0; p < 64u * 64u; ++p) {
            const f64 dr = set.baseColor[p * 4 + 0] - gr;
            const f64 dg = set.baseColor[p * 4 + 1] - gm;
            const f64 db = set.baseColor[p * 4 + 2] - gb;
            var += (dr * dr + dg * dg + db * db) / 3.0;
        }
        var = std::sqrt(var / 4096.0);
        std::printf("    %-20s std %.2f encoded\n", c.name, var);
        if (c.flat) CHECK(var < 0.5);      // a smooth surface carries no grain
        else        CHECK(var > 1.0);      // and everything else carries some

        // Normals: unit length everywhere (a normal map that is not unit is a
        // lighting bug in every surface that samples it).
        u32 badNormals = 0, tilted = 0;
        for (size_t p = 0; p < 64u * 64u; ++p) {
            const f32 x = (set.normal[p * 3 + 0] / 127.5f) - 1.0f;
            const f32 y = (set.normal[p * 3 + 1] / 127.5f) - 1.0f;
            const f32 z = (set.normal[p * 3 + 2] / 127.5f) - 1.0f;
            const f32 len = std::sqrt(x * x + y * y + z * z);
            if (std::fabs(len - 1.0f) > 0.03f) ++badNormals;
            if (std::fabs(x) > 0.01f || std::fabs(y) > 0.01f) ++tilted;
        }
        CHECK_EQ(badNormals, 0u);
        if (c.ripple)      CHECK(tilted > 200u);       // water ripples
        else if (c.flat)   CHECK_EQ(tilted, 0u);       // glass is flat by design
        else               CHECK(tilted > 1000u);      // real relief

        // ORM: the green channel's mean is the authored roughness, and metallic
        // is flat in blue.
        f64 rough = 0, metal = 0;
        for (size_t p = 0; p < 64u * 64u; ++p) {
            rough += set.orm[p * 3 + 1] / 255.0;
            metal += set.orm[p * 3 + 2] / 255.0;
        }
        rough /= 4096.0; metal /= 4096.0;
        CHECK(std::fabs(rough - c.roughness) < 0.08);
        CHECK(std::fabs(metal - c.metallic) < 0.02);
    }
}

// Verifies the *shipped* arrays, not just a round trip: the layers the runtime
// will bind, read out of `data/processed/textures/` by the runtime reader.  A
// fresh checkout has not built the world, so the case reports the skip loudly
// rather than passing quietly — `make all-checks` runs it after `make world`.
TEST(theBuiltMaterialArraysAreSelfConsistent) {
    const char* dir = "data/processed/textures";
    tex::TexArrayReader bc, nm, orm;
    std::string err;
    if (!bc.open(std::string(dir) + "/materials_basecolor.mumbaitex", true, &err)) {
        std::printf("    SKIP: %s (run `make world`)\n", err.c_str());
        return;
    }
    CHECK(nm.open(std::string(dir) + "/materials_normal.mumbaitex", true, &err));
    CHECK(orm.open(std::string(dir) + "/materials_orm.mumbaitex", true, &err));
    CHECK(bc.valid() && nm.valid() && orm.valid());
    if (!bc.valid() || !nm.valid() || !orm.valid()) return;

    // One layer per textured material, three arrays in lockstep, and every single
    // layer survived the whole-file hash above (that is what `true` asked for).
    CHECK(bc.layerCount() > 100);
    CHECK_EQ(nm.layerCount(), bc.layerCount());
    CHECK_EQ(orm.layerCount(), bc.layerCount());
    CHECK_EQ(bc.size(), 256u);
    CHECK(bc.type() == tex::MapType::BaseColor);
    CHECK(nm.type() == tex::MapType::Normal);
    CHECK(orm.type() == tex::MapType::ORM);

    u32 flatNormals = 0, badNormals = 0, degenerate = 0, flatAlbedo = 0;
    f32 minTile = 1e9f, maxTile = 0.0f;
    for (u32 i = 0; i < bc.layerCount(); ++i) {
        const tex::TexLayer* lb = bc.layer(i);
        const tex::TexLayer* ln = nm.layer(i);
        CHECK(lb && ln);
        if (!lb || !ln) continue;
        CHECK(std::fabs(lb->tileMetres - ln->tileMetres) < 1e-4f);   // same material
        minTile = std::min(minTile, lb->tileMetres);
        maxTile = std::max(maxTile, lb->tileMetres);

        // Albedo: the mean the record publishes must be the mean of the bytes.
        f32 m[3] = {0, 0, 0};
        CHECK(bc.layerMean(i, m, /*linearSpace=*/true));
        CHECK(std::fabs(m[0] - lb->meanR) < 1e-3f);
        CHECK(std::fabs(m[1] - lb->meanG) < 1e-3f);
        CHECK(std::fabs(m[2] - lb->meanB) < 1e-3f);
        if (lb->meanR <= 0.0f && lb->meanG <= 0.0f && lb->meanB <= 0.0f) ++degenerate;

        // Normals: unit length throughout, and *not* all flat on most layers.
        const u8* px = nm.pixels(i);
        u32 tilted = 0;
        for (u32 k = 0; k < 256u * 256u; k += 11) {
            const f32 x = (px[k * 3 + 0] / 127.5f) - 1.0f;
            const f32 y = (px[k * 3 + 1] / 127.5f) - 1.0f;
            const f32 z = (px[k * 3 + 2] / 127.5f) - 1.0f;
            if (std::fabs(std::sqrt(x * x + y * y + z * z) - 1.0f) > 0.03f) ++badNormals;
            if (std::fabs(x) > 0.01f || std::fabs(y) > 0.01f) ++tilted;
        }
        if (tilted == 0) ++flatNormals;

        // A tile must carry some albedo structure, unless it is one of the
        // deliberately flat surfaces — those are counted, not silently allowed:
        // at most a handful of the library may be flat.
        f32 lo = 1.0f, hi = 0.0f;
        const u8* bpx = bc.pixels(i);
        for (u32 k = 0; k < 256u * 256u; k += 7) {
            const f32 l = bpx[k * 4 + 1] / 255.0f;
            lo = std::min(lo, l);
            hi = std::max(hi, l);
        }
        if (hi - lo < 1.0f / 255.0f) ++flatAlbedo;
    }
    CHECK_EQ(badNormals, 0u);
    CHECK_EQ(degenerate, 0u);
    CHECK(flatNormals <= 8);        // glass, lamps, steel, water — a short list
    CHECK(flatAlbedo <= 8);
    CHECK(minTile > 0.3f && maxTile < 20.0f);
    std::printf("    %u shipped layers, tiles %.1f-%.1f m, %u flat normals\n",
                bc.layerCount(), static_cast<double>(minTile), static_cast<double>(maxTile),
                flatNormals);
}
