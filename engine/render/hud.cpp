//
//  The 5x7 font, the atlas, and the vertex builder.  See hud.h for why this
//  exists at all; this file is the data and the arithmetic.
//
//  THE FONT.  Rows are top to bottom, each row is five bits, bit 4 is the
//  leftmost pixel.  It is written out longhand rather than generated from a
//  font file because it has to work on a machine with no font, no library and no
//  network — and because `tests/test_render.cpp` can then assert that every
//  glyph has ink (a missing glyph is a silent blank in the middle of a status
//  line, which is exactly the failure this panel exists to prevent).
// =============================================================================
