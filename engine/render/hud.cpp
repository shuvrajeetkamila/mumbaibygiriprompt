void buildFontAtlas(std::vector<u8>& out) {
    out.assign(static_cast<size_t>(kAtlasW) * kAtlasH, 0);
    for (u32 g = 0; g < kGlyphCount; ++g) {
        const u32 cx = (g % kAtlasCols) * kCellW;
        const u32 cy = (g / kAtlasCols) * kCellH;
        for (u32 row = 0; row < kGlyphH; ++row) {
            for (u32 col = 0; col < kGlyphW; ++col) {
                if (!glyphLit(g, row, col)) continue;
                out[static_cast<size_t>(cy + row) * kAtlasW + cx + col] = 255;
            }
        }
    }
    // The cell after the last glyph is solid: it is what a rectangle samples.
    const u32 cx = (kSolidCell % kAtlasCols) * kCellW;
    const u32 cy = (kSolidCell / kAtlasCols) * kCellH;
    for (u32 row = 0; row < kCellH; ++row) {
        for (u32 col = 0; col < kCellW; ++col) {
            out[static_cast<size_t>(cy + row) * kAtlasW + cx + col] = 255;
        }
    }
}

// --- the CPU rasteriser ------------------------------------------------------
u8 glyphRow(char c, u32 row) {
    const i32 index = static_cast<u8>(c) - static_cast<i32>(kFirstGlyph);
    if (index < 0 || index >= static_cast<i32>(kGlyphCount) || row >= kGlyphH) return 0;
    return static_cast<u8>(kFont[static_cast<u32>(index)][row] & ((1u << kGlyphW) - 1u));
}

void blitRect(u8* pixels, i32 stride, i32 clipW, i32 clipH, i32 x, i32 y, i32 w, i32 h,
              u8 value) {
    if (!pixels || stride <= 0 || clipW <= 0 || clipH <= 0 || w <= 0 || h <= 0) return;
    const i32 x0 = x < 0 ? 0 : x;
    const i32 y0 = y < 0 ? 0 : y;
    const i64 x1 = static_cast<i64>(x) + w;
    const i64 y1 = static_cast<i64>(y) + h;
    const i32 xEnd = static_cast<i32>(x1 < clipW ? x1 : clipW);
    const i32 yEnd = static_cast<i32>(y1 < clipH ? y1 : clipH);
    for (i32 py = y0; py < yEnd; ++py) {
        u8* line = pixels + static_cast<size_t>(py) * static_cast<size_t>(stride);
        for (i32 px = x0; px < xEnd; ++px) line[px] = value;
    }
}

i32 textPixelWidth(const std::string& text, u32 scale) {
    return static_cast<i32>(text.size()) * static_cast<i32>(kCellW) * static_cast<i32>(scale);
}

i32 textPixelHeight(u32 scale) {
    return static_cast<i32>(kCellH) * static_cast<i32>(scale);
}

void blitText(u8* pixels, i32 stride, i32 clipW, i32 clipH, i32 x, i32 y,
              const std::string& text, u32 scale, u8 value) {
    if (!pixels || scale == 0) return;
    const i32 step = static_cast<i32>(scale);
    i32 penX = x;
    i32 penY = y;
    for (char ch : text) {
        if (ch == '\n') {
            penX = x;
            penY += static_cast<i32>(kCellH) * step;
            continue;
        }
        for (u32 row = 0; row < kGlyphH; ++row) {
            const u8 bits = glyphRow(ch, row);
            if (!bits) continue;
            for (u32 col = 0; col < kGlyphW; ++col) {
                if (!((bits >> (kGlyphW - 1 - col)) & 1u)) continue;
                blitRect(pixels, stride, clipW, clipH, penX + static_cast<i32>(col) * step,
                         penY + static_cast<i32>(row) * step, step, step, value);
            }
        }
        penX += static_cast<i32>(kCellW) * step;
    }
}

f32 hudTextWidth(const std::string& text, f32 scale) {
    return static_cast<f32>(text.size()) * static_cast<f32>(kCellW) * scale;
}

f32 hudLineHeight(f32 scale) {
    return static_cast<f32>(kCellH) * scale;
}

u32 buildHudVertices(const HudFrame& frame, f32 viewportW, f32 viewportH,
                     std::vector<HudVertex>& out) {
    const u32 before = static_cast<u32>(out.size());
    const f32 solidU = static_cast<f32>(kSolidU0) + 0.5f;
    const f32 solidV = static_cast<f32>(kSolidV0) + 0.5f;

    // Panels first: the text is meant to be read against them, and the pipeline
    // draws in submission order with no depth test.
    for (const HudRect& r : frame.rects) {
        if (r.w <= 0.0f || r.h <= 0.0f) continue;
        pushQuad(out, r.x, r.y, r.x + r.w, r.y + r.h, solidU, solidV, solidU, solidV, r.colour);
    }

    for (const HudLine& line : frame.lines) {
        if (line.scale <= 0.0f) continue;
        f32 penX = line.x;
        f32 penY = line.y;
        for (char ch : line.text) {
            if (ch == '\n') {
                penX = line.x;
                penY += hudLineHeight(line.scale);
                continue;
            }
            const i32 code = static_cast<u8>(ch);
            const i32 index = code - static_cast<i32>(kFirstGlyph);
            if (index >= 0 && index < static_cast<i32>(kGlyphCount)) {
                const u32 g = static_cast<u32>(index);
                const u32 cx = (g % kAtlasCols) * kCellW;
                const u32 cy = (g / kAtlasCols) * kCellH;
                for (u32 row = 0; row < kGlyphH; ++row) {
                    for (u32 col = 0; col < kGlyphW; ++col) {
                        if (!glyphLit(g, row, col)) continue;
                        const f32 x0 = penX + static_cast<f32>(col) * line.scale;
                        const f32 y0 = penY + static_cast<f32>(row) * line.scale;
                        // A glyph pixel is a quad inside the cell's single-pixel
                        // footprint, so the uv range is one texel: sampling it
                        // with a linear filter at any scale gives the same mask.
                        if (x0 >= viewportW || y0 >= viewportH) continue;
                        pushQuad(out, x0, y0, x0 + line.scale, y0 + line.scale,
                                 static_cast<f32>(cx + col), static_cast<f32>(cy + row),
                                 static_cast<f32>(cx + col + 1), static_cast<f32>(cy + row + 1),
                                 line.colour);
                    }
                }
            }
            penX += static_cast<f32>(kCellW) * line.scale;
            if (penX > viewportW) penX = line.x;   // wrap rather than run off
        }
    }
    return static_cast<u32>(out.size()) - before;
}

