inline bool glyphLit(u32 index, u32 row, u32 col) {
    if (index >= kGlyphCount || row >= kGlyphH || col >= kGlyphW) return false;
    return (kFont[index][row] >> (kGlyphW - 1 - col)) & 1u;
}

void pushQuad(std::vector<HudVertex>& out, f32 x0, f32 y0, f32 x1, f32 y1, f32 u0, f32 v0,
              f32 u1, f32 v1, u32 colour) {
    const f32 ax = 1.0f / static_cast<f32>(kAtlasW);
    const f32 ay = 1.0f / static_cast<f32>(kAtlasH);
    HudVertex a{x0, y0, u0 * ax, v0 * ay, colour};
    HudVertex b{x1, y0, u1 * ax, v0 * ay, colour};
    HudVertex c{x1, y1, u1 * ax, v1 * ay, colour};
    HudVertex d{x0, y1, u0 * ax, v1 * ay, colour};
    out.push_back(a); out.push_back(b); out.push_back(c);
    out.push_back(a); out.push_back(c); out.push_back(d);
}

