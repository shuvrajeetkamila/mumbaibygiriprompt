#!/usr/bin/env python3
"""Turns compiled SPIR-V into a C++ header.

The renderer has no asset loader: shaders are compiled by glslc at build time and
embedded in the binary, so a device that can start the engine can always find its
shaders, whatever the APK's asset layout turns out to be.
"""
import os
import sys

# The table is the interface between the shader directory and the renderer's C++
# symbols: a shader that is compiled but not named here is a shader that is not in
# the binary, and the failure is a runtime "shader missing" for a module that is
# sitting in the build directory.  Adding a shader means adding a line here, and
# `host_check` counts them so that the omission is caught by a check and not by a
# device.
NAMES = {
    "world.vert": "kWorldVertSpv",
    "world.frag": "kWorldFragSpv",
    "water.frag": "kWaterFragSpv",
    "sky.vert": "kSkyVertSpv",
    "sky.frag": "kSkyFragSpv",
    "post.vert": "kPostVertSpv",
    "post.frag": "kPostFragSpv",
    "traffic.vert": "kTrafficVertSpv",
    "traffic.frag": "kTrafficFragSpv",
    "hud.vert": "kHudVertSpv",
    "hud.frag": "kHudFragSpv",
}


def main() -> int:
    if len(sys.argv) < 3:
        print("usage: embed_spirv.py <out.h> <spirv-dir>", file=sys.stderr)
        return 2
    out_path, spv_dir = sys.argv[1], sys.argv[2]
    lines = [
        "// Generated by tools/embed_spirv.py - do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
    ]
    missing = []
    for name, symbol in sorted(NAMES.items()):
        path = os.path.join(spv_dir, name + ".spv")
        words = []
        if os.path.isfile(path):
            data = open(path, "rb").read()
            if len(data) % 4 == 0:
                words = [
                    int.from_bytes(data[i:i + 4], "little")
                    for i in range(0, len(data), 4)
                ]
        else:
            missing.append(name)
        lines.append("inline constexpr std::uint32_t %s[] = {" % symbol)
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
        if not words:
            lines.append("    0x00000000u,  // placeholder: no SPIR-V was available")
        lines.append("};")
        lines.append("inline constexpr std::size_t %sWords = %d;" % (symbol, len(words)))
        lines.append("")
    open(out_path, "w").write("\n".join(lines))
    if missing:
        print("warning: no SPIR-V for %s" % ", ".join(sorted(missing)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
